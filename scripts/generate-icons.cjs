// Official Font Awesome Free 5.6.3 SVG definitions. See LICENSES/FontAwesome-NOTICE.md.
// Generated assets are committed so consumers do not need build-time dependencies.
const { readFileSync, writeFileSync } = require('node:fs')
const icons = ['arrow-left', 'arrow-right', 'undo', 'step-backward', 'step-forward']
const data = Object.fromEntries(icons.map(name => {
    const key = 'fa' + name.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join('')
    const { icon } = require(`@fortawesome/free-solid-svg-icons/${key}.js`)[key]
    return [name, { viewBox: `0 0 ${icon[0]} ${icon[1]}`, paths: [].concat(icon[4]) }]
}))
const target = 'src/iconDefinitions.js'
const content = '// Generated by scripts/generate-icons.cjs; Font Awesome Free 5.6.3 by Fonticons, Inc., CC BY 4.0.\n'
    + '// See LICENSES/FontAwesome-NOTICE.md. Do not edit paths by hand.\n'
    + `export const iconDefinitions = ${JSON.stringify(data, null, 4)}\n`
let previous
try { previous = readFileSync(target, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
if (previous === content) process.exit(0)
if (process.argv.includes('--check')) {
    console.error(`${target} is out of date; run node scripts/generate-icons.cjs`)
    process.exit(1)
}
writeFileSync(target, content)
console.log(`Generated ${target}`)
